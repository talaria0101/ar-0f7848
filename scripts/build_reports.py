#!/usr/bin/env python3
"""Build data/inventory.tsv, reports/01-inventory.md and reports/02-findings.md
from data/providers.json, data/facts/*.json, data/snapshots/*/meta.json and
the probe verdicts in scripts/verdict.py. Nothing is typed into the tables by hand.
"""
import collections, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from verdict import classify  # noqa: E402

NE = "not established"
CLAIMS = ("auth", "rate_limit", "cost", "data_license")


def load():
    provs = json.load(open(os.path.join(ROOT, "data", "providers.json")))
    rows = []
    for p in provs:
        s = p["slug"]
        f = json.load(open(os.path.join(ROOT, "data", "facts", s + ".json")))
        m = json.load(open(os.path.join(ROOT, "data", "snapshots", s, "meta.json")))
        rows.append({**p, **f, "verdict": classify(s), "meta": m})
    return rows


def cell(s, n=110):
    s = " ".join(str(s).split()).replace("|", "/")
    return s if len(s) <= n else s[: n - 3] + "..."


def tsv(rows):
    cols = ["slug", "name", "category", "auth", "cost", "probe_status", "verdict", "rate_limit",
            "data_license", "bulk_access", "docs", "probe"]
    with open(os.path.join(ROOT, "data", "inventory.tsv"), "w") as f:
        f.write("\t".join(cols) + "\n")
        for r in rows:
            f.write("\t".join(" ".join(str(r[c]).split()) for c in cols) + "\n")


def inventory(rows):
    out = ["# 01 Inventory", "",
           f"{len(rows)} providers. Generated by `scripts/build_reports.py` from `data/facts/`; every value that is not "
           f"`{NE}` is backed by a verbatim quote in `data/snapshots/<slug>/` (enforced by `scripts/test_facts.py`).", "",
           "Columns: **probe** is what one anonymous call returned from the capture machine (verdict from the captured body, "
           "HTTP status in brackets). **auth** is what the documentation or refusal text supports; it can differ from the "
           "probe when the probe was blocked (see `02-findings.md`).", ""]
    by = collections.defaultdict(list)
    for r in rows:
        by[r["category"]].append(r)
    for cat in sorted(by):
        out += [f"## {cat} ({len(by[cat])})", "",
                "| Provider | Auth | Cost | Documented rate limit | Data license | Probe |",
                "|---|---|---|---|---|---|"]
        for r in sorted(by[cat], key=lambda x: x["slug"]):
            out.append(f"| [{cell(r['name'], 45)}]({r['docs']}) | {r['auth']} | {r['cost']} | {cell(r['rate_limit'], 90)} "
                       f"| {cell(r['data_license'], 60)} | {r['verdict']} [{r['probe_status']}] |")
        out.append("")
    open(os.path.join(ROOT, "reports", "01-inventory.md"), "w").write("\n".join(out) + "\n")


def findings(rows):
    n = len(rows)
    out = ["# 02 Findings", "", f"All counts are over the {n} providers in `data/providers.json`, computed by "
           "`scripts/build_reports.py`. Capture date and machine are in each `meta.json` (`fetched_at`).", ""]
    v = collections.Counter(r["verdict"] for r in rows)
    out += ["## 1. What one anonymous call returned", "", "| Verdict | Count | Providers |", "|---|---|---|"]
    for k in ("data", "refused", "challenge", "unreachable", "other"):
        names = ", ".join(r["slug"] for r in rows if r["verdict"] == k)
        out.append(f"| {k} | {v[k]} | {cell(names, 700)} |")
    out += ["", "`data` = HTTP 200 and a parseable record body. `refused` = 401/403/429 with an API-level message. "
            "`challenge` = bot-wall page. `unreachable` = the capture machine's egress proxy refused the host (status 0 or an "
            "empty 502); this says nothing about whether the service is up. `other` = wrong endpoint, SPA shell or 200 with an error body.", ""]
    a = collections.Counter(r["auth"] for r in rows)
    out += ["## 2. Access model (from documentation or refusal text)", "", "| auth | Count |", "|---|---|"]
    out += [f"| {k} | {a[k]} |" for k in ("none", "key-free", "key-approval", "key-paid", "ip-allowlist", "unreachable")]
    out += ["", "Keyless providers whose live probe was NOT `data` (their `none` rests on documentation, not on an observed response): "
            + (", ".join(f"{r['slug']} ({r['verdict']})" for r in rows if r["auth"] == "none" and r["verdict"] != "data") or "none") + ".", ""]
    out += ["## 3. What the pages did not say", "", "| Claim | Providers with a documented value | Providers where it is not established |", "|---|---|---|"]
    for c in CLAIMS:
        have = sum(1 for r in rows if r[c] != NE and not (c == 'auth' and r[c] == 'unreachable'))
        out.append(f"| {c} | {have} | {n - have} |")
    out += ["", "A page that did not state a value is a gap in the capture, not evidence the provider has no limit, cost or license. "
            "Every `not established` has its reason in the provider's `not_established` field in `data/facts/<slug>.json`.", ""]
    out += ["## 4. Rate-limit headers observed on the probe response", "",
            "Headers matching `ratelimit|retry-after|quota` on the probe response, beside the limit the documentation was captured stating. "
            "The probe ran from one shared egress IP, so these describe that path, not every client.", "",
            "| Provider | Observed headers | Documented (captured) |", "|---|---|---|"]
    for r in rows:
        h = {k: x for k, x in r["meta"]["probe"]["ratelimit_headers"].items() if "ratelimit" in k.lower() or "retry" in k.lower()}
        if h:
            out.append(f"| {r['slug']} | {cell(', '.join(f'{k}={x}' for k, x in h.items()), 150)} | {cell(r['rate_limit'], 120)} |")
    out += ["", "Where the two disagree, the capture shows both and neither is overridden: documentation can be stale and a header can "
            "describe a different tier than the one the docs name. `openaire` (header 7199 on an anonymous call, docs say 60 per hour "
            "anonymous), `scite` (header 60 per minute, docs 40 per minute without a token) and `smithsonian` "
            "(header 10, docs 30 per hour for DEMO_KEY) disagree in this capture.", ""]
    out += ["## 5. Providers that returned 200 but not records", ""]
    for r in rows:
        if r["probe_status"] == 200 and r["verdict"] != "data":
            out.append(f"- `{r['slug']}`: {cell(r['probe_observation'], 260)}")
    out += [""]
    out += ["## 6. Per-provider limits recorded by the evidence pass", "",
            "Each of these is a `not_established` field quoted from `data/facts/`:", ""]
    for r in rows:
        out.append(f"- `{r['slug']}`: {cell(r['not_established'], 300)}")
    out += [""]
    open(os.path.join(ROOT, "reports", "02-findings.md"), "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    os.makedirs(os.path.join(ROOT, "reports"), exist_ok=True)
    rows = load()
    tsv(rows)
    inventory(rows)
    findings(rows)
    print(len(rows), "providers; reports written")
